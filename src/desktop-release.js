// Desktop launcher release channel (GitHub Releases).
//
// `dpx` and the desktop shell both consume this contract; the machine-readable
// shape is specified in `docs/desktop-release.md`. The desktop shell implements
// the same rules in Rust (`desktop-shell/src-tauri/src/update.rs`).
//
// A published desktop release has the tag `desktop-v<version>` and carries:
//   - `desktop-latest.json`                     the manifest below
//   - `DSH-DeepSeek-Harness-Desktop-<version>-x64.exe`   the launcher
//
// Manifest (`DPXDesktopRelease`, schemaVersion 1):
//   { schemaVersion, kind, channel, version, tag, platform, assetName,
//     assetUrl, sha256, size, publishedAt, notes, sig? }
//
// `sig` is an **optional** publisher signature (`{ algorithm: 'ed25519',
// signature: <base64> , keyId? }`). It is never produced here; this module only
// verifies it, and only when a trusted public key is configured. The signed
// message is defined by `desktopSignatureMessage()` and deliberately covers the
// digest instead of the manifest bytes, because the manifest is generated by
// more than one tool (PowerShell `ConvertTo-Json` and Node `JSON.stringify`
// disagree on bytes) while the digest is a single lowercase hex string.
//
// The install stamp `desktop/.dpx-desktop.json` is written by two programs:
// this module (ISO `installedAt`) and the desktop shell (epoch
// `installedAtMillis`, `update.rs:515`). Readers accept both shapes, and the
// stamp `schemaVersion` is validated against `DESKTOP_STAMP_SCHEMA_VERSIONS`
// instead of being accepted silently.

